        Spacer(modifier = Modifier.height(20.dp))

        Button(onClick = onRetry) {
            Icon(imageVector = Icons.Default.Refresh, contentDescription = null)
            Spacer(modifier = Modifier.width(8.dp))
            Text("Retry Connection")
        }
    }
}
